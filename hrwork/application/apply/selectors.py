"""Селекторы ОТКЛИКА hh.ru и бюджет подтверждения — ОДИН источник на оба боевых пути.

До 23.09.2026 один и тот же элемент отклика адресовался по-разному в двух модулях
(`autoclick._RESPONSE_SUBMIT`/`_RESPONSE_LETTER` против `forms._SUBMIT`/`_LETTER`), а бюджет
подтверждения расходился (10 с у одного отклика против 6×2 с ≈ 12 с у дренажа анкет), причём
тексты логов жёстко зашивали числа. HH меняет разметку — замечал один путь, второй молча
переставал вписывать обязательное письмо, кнопка оставалась `disabled`, и прогон рапортовал
«отклик НЕ подтверждён» (класс из `docs/errors.md`, 03-04.08.2026).

Почему submit — ОБЪЕДИНЁННАЯ строка, а не только попап: когда в поп-апе раскрыт слот
сопроводительного, кнопка меняет data-qa на `vacancy-response-letter-submit`; короткий
селектор оставил бы клик без кнопки на самом частом пути (письмо обязательно) — именно
поэтому объединённый вариант и выстрадан в `apply_one`. Соседние пути берут тот же локатор.

Строка с запятой внутри ОДНОГО локатора, НЕ кортеж: перебор кортежа/строки посимвольно
кликал бы `locator('a')` — cookie-ссылку, и открывал лавину вкладок. Обращение — только
через `.first`.

Почему письмо — БЕЗ тега `textarea`: тот же атрибут стоит на самом поле ввода, а
тег-квалификатор ломается при смене контрола (`input` <-> `textarea`). Оба пути делают по
этому локатору только `fill`/`input_value` под suppress, поэтому лишнее совпадение
деградирует ровно в тот же подавленный «поле не нашли», что и отсутствие элемента, —
а тег-квалификатор, наоборот, молча пропустил бы ОБЯЗАТЕЛЬНОЕ письмо (инцидент 03.08.2026).

`CONFIRM_BUDGET_S` — большее из двух прежних значений (12 с): объединение не имеет права
УЖЕСТОЧАТЬ обязательный путь. Расширение ожидания только уменьшает ложные SKIP: HH
подтверждал отклик на 11-й секунде, когда путь с 10 с уже вернул SKIP и отклик уходил в
журнал мимо квоты (см. `hh_sync._reconciled_today`).
"""
import contextlib
from typing import Any

# Кнопка подтверждения отклика в поп-апе (одна CSS-строка через запятую, см. докстринг).
RESPONSE_SUBMIT = ('[data-qa="vacancy-response-letter-submit"], '
                   '[data-qa="vacancy-response-submit-popup"]')
# Поле сопроводительного на странице/в модалке отклика.
RESPONSE_LETTER = '[data-qa="vacancy-response-popup-form-letter-input"]'
# Маркеры успеха: чат-топик на карточке ИЛИ текст «Вы откликнулись» (любой из двух).
RESPONSE_DONE_MARKER = '[data-qa="vacancy-response-link-view-topic"]'
RESPONSE_DONE_TEXT = "Вы откликнулись"

CONFIRM_BUDGET_S = 12        # бюджет ожидания подтверждения отклика, сек (единый на оба пути)
CONFIRM_POLL_S = 2           # шаг опроса в рамках бюджета (HH перерисовывает карточку с лагом)


def response_confirmed(page: Any) -> bool:
    """Одноразовая проверка: отклик подтверждён (чат-топик или «Вы откликнулись»)."""
    with contextlib.suppress(Exception):
        return bool(page.locator(RESPONSE_DONE_MARKER).count()
                    or page.get_by_text(RESPONSE_DONE_TEXT).count())
    return False


def wait_response_confirmed(page: Any) -> bool:
    """Ждать подтверждение отклика до `CONFIRM_BUDGET_S`, опрашивая `response_confirmed`.

    ЕДИНСТВЕННОЕ ожидание на оба пути (`autoclick.apply_one` и дренаж анкет): HH
    перерисовывает карточку с лагом, и мгновенная проверка принимала ушедший отклик за
    неотправленный (инцидент 134804227, 2026-07-22 — подтверждение не успело за 2 с).
    Проверяем ПЕРВЫМ делом: если маркер уже на месте, ждать нечего. False — не подтвердился."""
    checks = CONFIRM_BUDGET_S // CONFIRM_POLL_S
    for remaining in range(checks, -1, -1):
        if response_confirmed(page):
            return True
        if remaining:
            try:
                page.wait_for_timeout(CONFIRM_POLL_S * 1000)
            except Exception:        # контекст рухнул — ждать больше нечего
                return False
    return False
