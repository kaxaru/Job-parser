# Маркеры удалёнки в тексте вакансии: HH не всегда проставляет тег "remote", но в описании
# формат часто указан словами. Стемы с двойной "н" ("удалённ"/"удаленн") и "удалёнк"/"удаленк"
# не пересекаются с "удаление"/"удалить" (там одна "н") — ложных срабатываний нет.
# Доменный классификатор (не презентация): нужен и View-ленте, и отбору откликов autoclick.
REMOTE_MARKERS = (
    "удалённ", "удаленн", "удалёнк", "удаленк",
    "remote", "дистанцион", "из дома", "home office", "хоум офис",
    "work from home", "wfh", "из любой точки",
)


def has_remote(text: str) -> bool:
    """Есть ли в тексте вакансии словесный маркер удалёнки (когда тег remote не проставлен)."""
    t = text.lower()
    return any(m in t for m in REMOTE_MARKERS)


def _salary_mid(sal: dict[str, Any] | None) -> tuple[int | None, int | None, int | None]:
    """(from, to, mid) — уже net (gross→net внутри Salary VO)."""
    s = Salary.from_raw(sal)
    return s.net_triple() if s else (None, None, None)


def _prescreen_literal(alt: str) -> str:
    """Гарантированная ведущая литеральная подстрока одной альтернативы regex.
    Если её нет в тексте — альтернатива заведомо не сматчит (необходимое условие)."""
    s = alt.replace(r"\b", "")
    lit: list[str] = []
    i = 0
    while i < len(s):
        c = s[i]
        if c == "\\":
            if i + 1 >= len(s):
                break
            if i + 2 < len(s) and s[i + 2] in "?*{":   # экранированный символ квантифицирован -> опционален
                break
            lit.append(s[i + 1])
            i += 2
            continue
        if c in "([.":                                  # группа/класс/любой символ -> стоп
            break
        if i + 1 < len(s) and s[i + 1] in "?*{":        # символ опционален/повторяем -> стоп
            break
        if c in "+)":
            break
        lit.append(c)
        i += 1
    return "".join(lit)


def _build_screened() -> list[tuple[str, "re.Pattern[str]", tuple[str, ...] | None]]:
    """(тег, compiled regex, литералы-пресина | None) — считается ОДИН раз при импорте.
    Пресин включаем, только если каждая альтернатива даёт ядро >=2 симв.; иначе None
    -> regex зовётся всегда (корректность важнее микро-оптимизации одного паттерна)."""
    out = []
    for tech, pat in TECH_PATTERNS.items():
        lits = [_prescreen_literal(a) for a in pat.split("|")]
        screen = tuple(lits) if all(len(x) >= 2 for x in lits) else None
        out.append((tech, re.compile(pat), screen))
    return out


_SCREENED = _build_screened()


# «Для работы потребуется смартфон или планшет с ОС iOS или Android» — требование к
# УСТРОЙСТВУ соискателя (крауд/промо/курьеры/банкиры), а не стек. Снимаем клаузу целиком
# (обе ОС в одной фразе), иначе один такой абзац вешал Android/iOS на расклейщика листовок,
# а фолбэк роли делал его «Разработчиком». Другие упоминания ОС в тексте не трогаем —
# у настоящей мобильной вакансии стек назван и вне этой фразы, тег выживает.
_DEVICE_CLAUSE = re.compile(r'(?:смартфон|планшет|телефон|гаджет|устройств\w*)[^.!?;]{0,70}', re.I)
_DEVICE_OS = re.compile(r'\b(?:ios|android)\b', re.I)


def _strip_device_req(text: str) -> str:
    return _DEVICE_CLAUSE.sub(
        lambda m: ' ' if _DEVICE_OS.search(m.group(0)) else m.group(0), text)


# Сигнатура словаря стека. Техи кешируются в raw (`_techs`), и если поменять TECH_PATTERNS
# или логику пресина, кеш обязан протухнуть САМ — иначе лента месяцами показывала бы стек,
# посчитанный старыми правилами, и никто бы не заметил. Хеш считается по исходнику словаря
# ПЛЮС версия алгоритма: правка _detect_techs без правки паттернов тоже требует пересчёта.
_DETECT_ALGO_VERSION = 1
DETECT_SIG = hashlib.blake2s(
    (repr(sorted(TECH_PATTERNS.items())) + f"|v{_DETECT_ALGO_VERSION}").encode("utf-8"),
    digest_size=6,
).hexdigest()


def _detect_techs(text: str) -> list[str]:
    # Подстрочный пресин (str.__contains__ — дешёвый C-поиск) отсекает заведомо
    # непрошедшие паттерны, regex подтверждает прошедшие. Семантика тождественна
    # «re.search по всем TECH_PATTERNS» (проверено на 34k: 0 расхождений), но ~17x быстрее
    # (137 c -> 8 c): раньше на КАЖДУЮ вакансию гонялись все 55 regex.
    t = _strip_device_req(text.lower())
    res = []
    for tech, rx, screen in _SCREENED:
        if screen is not None and not any(lit in t for lit in screen):
            continue
        if rx.search(t):
            res.append(tech)
    return res


# Роль — по ТАЙТЛУ (regex прекомпилированы один раз). Сниппет не берём: тело JD
# упоминает «тестирование/безопасность/ML» и ломает классификацию (backend-вакансия
# со словом «тестирование» в требованиях уехала бы в QA).
# Ярлык ROLE_PATTERNS -> Role резолвим ЗДЕСЬ, на импорте: незнакомый ключ (config без члена
# Role) роняет модуль сразу при загрузке — fail-fast, а не ValueError после часов сбора.
_ROLE_RX = [(Role.from_label(role), re.compile(pat, re.I)) for role, pat in ROLE_PATTERNS.items()]

# ЖЁСТКИЙ не-IT: тайтлы, которые НИКОГДА не IT (транспорт/доставка/склад/сервис/ритейл).
# Применяем БЕЗУСЛОВНО — даже при тех-теге: ложный тег (напр. Android/iOS от «работа с
# приложением» в сниппете продавца-кассира) не должен делать его разработчиком.
_HARD_NON_IT = re.compile(
    r'\bводитель|\bкурьер|велокурьер|\bтакси\b|самокат|доставщик|грузчик|кладовщик|'
    r'комплектовщик|грузоперевоз|экспедитор|\bповар\b|официант|бариста|уборщ|охранник|'
    r'продав|кассир|мерчанд|мерченд|товаровед|фасовщик|приёмщик|приемщик|комплектов|'
    r'пекарь|кондитер|флорист|парикмахер|маникюр|\bбьюти|разнорабоч|сборщик заказ|'
    # поддержка / преподавание / продажи — не инженерные роли, но JD часто содержит «Python/SQL»
    # -> ложно уходили в «Разработчик» (кейс «Яндекс Крауд: Поддержка», «Менеджер по продажам»).
    # `.{0,20}` ловит слово между: «Специалист ТЕХНИЧЕСКОЙ поддержки».
    r'специалист.{0,20}поддержк|техническ\w*\s+поддержк|служб\w*\s+поддержк|'
    r'преподавател|репетитор|менеджер\w*\s+по\s+продаж|'
    # ФИЗИЧЕСКАЯ безопасность (СКУД/видеонаблюдение/пожарка) и инженерные системы зданий:
    # роль Security ловит их по слову «безопасн», хотя это не ИБ.
    r'средств\w*\s+безопасн|жизнеобеспечен|'
    # финансовый/бизнес-аудит. НЕ трогаем технический аудит: «Аудитор смарт-контрактов»,
    # «Аудитор защищённости приложений (AppSec)», «Аудитор информационной безопасности»,
    # «Аудитор направления контейнеризации» — настоящие IT-роли.
    r'внутренн\w*\s+аудит|цифровы\w*\s+технологи\w*\s+аудит|аудит\w*\s+бизнес.?процесс|'
    r'аудитор.?аналитик|'
    # юристы / кадры / маркетинг — доменные роли, тех-слова попадают из JD
    r'юрист|юрискон|рекрут|hr.?менеджер|менеджер\w*\s+по\s+персоналу|отдел\w*\s+кадров|'
    r'кадров\w*\s+делопроизводств|маркетолог|'
    # медиа/маркетинг: рилсмейкер, монтажёр, контент-менеджер, SMM, копирайтер, таргетолог.
    # Часто «в IT» прямо в тайтле («Рилсмейкер / Монтажер коротких роликов в IT»), плюс
    # тех-слова в JD -> уезжали в «Разработчика». Берём именно РОЛЬ: «монтажёр» (видео), но
    # НЕ «монтаж» — иначе задели бы «инженера-технолога по электромонтажу».
    r'рилс|\breels\b|монтаж[ёе]р|видеограф|контент.?менеджер|\bsmm\b|копирайт|таргетолог|'
    # добыча/финучёт: «Инженер-аналитик по разработке месторождений», «Аналитик нефтегаза»,
    # «Бухгалтер …». Роль-существительное (аналитик/инженер/бухгалтер) уводило их в IT.
    # `бурени`/`геолог` НЕ берём: «инженер-программист автоматизации бурения» и «аналитик
    # данных по геологоразведке» — настоящие IT-вакансии.
    r'месторожден|нефтяник|нефтегаз|бухгалтер|'
    # SEO/маркетинг: «Automation-first SEO Operator», «Middle SEO-специалист / SEO-оптимизатор».
    # Автоматизируют выдачу скриптами -> в JD Python/JS, из-за чего уезжали в «Разработчика».
    # Целимся в РОЛЬ-существительное: «Программист для автоматизации задач SEO-отдела» —
    # настоящая dev-вакансия и проходить обязана.
    r'seo[\s\-]{0,3}(?:специалист|оптимизатор|operator|lead|аналитик|менеджер)|'
    r'(?:специалист|оптимизатор)[\s\-]{0,3}по[\s\-]{0,3}seo|'
    # образование/методология: педагог, методист, тьютор-наставник школ программирования.
    # Учат Python/робототехнике -> в JD полно тех-слов, поэтому уезжали в «Разработчика»
    # («Педагог дополнительного образования (Программирование)», «IT Методист»).
    r'педагог|методист|тьютор|'
    # академические подработки: «Автор студенческих работ по направлению …» — тайтл называет
    # предметную область (мат.моделирование/численные методы), из-за чего выглядел техническим
    r'студенческ\w*\s*работ|\bреферат|диссертац|'
    # синие воротнички / стройка / КИПиА — по анализу почти 0 IT-совпадений
    r'слесар|монтажник|\bэлектрик|сантехник|сварщик|токарь|фрезеров|наладчик|прораб|'
    r'геодез|сметчик|проектировщик|машинист|кипиа|киповец|штукатур|\bмаляр|каменщик|'
    r'бетонщик|арматурщик|стропальщик|\bбурильщик|горнорабоч|\bшвея\b|закройщик|'
    # стройка/инженерные системы/лаборатория (токен-анализ: IT-совпадения — мусор)
    # «инженер-испытатель» — hardware/стендовые испытания, не ПО-тестирование (БАГ 22.07:
    # отклик ушёл; язык из JD дал DEVELOPER-фолбэк). (?!ьн) щадит «испытательный срок»
    r'строительн|сооружен|электромонтёр|электромонтер|лаборант|испытател(?!ьн)|вентиляц|отоплен|'
    r'котельн|водоснабж|канализац|благоустройств|озеленен|дорожн\w*\s*строит',
    re.I,
)


def is_hard_non_it(name: str) -> bool:
    """Тайтл заведомо не-IT (транспорт/ритейл/стройка/…). Для отсева на этапе сбора
    ДО медленного enrich: по анализу такие тайтлы дают ~0 ложных отсевов реального IT."""
    return bool(_HARD_NON_IT.search(name or ""))
# КРАУД/РАЗМЕТКА: подработка на разметке данных и обучении моделей. Тайтл честно матчит
# ROLE_PATTERNS («AI-тренер» -> Data/ML, «крауд-тестирование» -> QA), но инженерной работы
# здесь нет: это оценка ответов нейросети и разметка. Нанимают так не только Яндекс Крауд —
# признак портальный (Сбер/Т-Банк тоже), поэтому правило по СУТИ работы, а не по компании.
# Применяем ДО ROLE_PATTERNS и безусловно: тех-тег («ML/AI» от слова «нейросеть») тут ничего
# не значит. «Врач/юрист/биолог для обучения нейросетей» — предметные эксперты, не Data/ML.
_GIG_NON_IT = re.compile(
    r'для обучения нейросет|обучени\w*\s+(?:ии|нейросет)|\bai.?тренер|\bии.?тренер|'
    r'крауд.?тест|краудсорс|разметчик|разметк\w*\s*данных|\bасессор|\bтолок',
    re.I,
)


# МЯГКИЙ не-IT: слова, где «разработчик/инженер» бывает не-IT (химик/технолог/
# конструктор РЭА). Применяем ТОЛЬКО без тех-тега — с языком в стеке это всё же IT.
_SOFT_NON_IT = re.compile(r'хими|технолог|конструктор|рецептур', re.I)

# КРЕАТИВ/МАРКЕТИНГ: продюсер/режиссёр/монтажёр/видеограф/SMM/маркетолог/контент/копирайтер —
# НЕ инженерные роли даже с баззвордом «AI» в тайтле («Продюсер AI видео», «AI-маркетолог»).
# Роль определяется РАБОТОЙ, а не тегом (как _GIG_NON_IT). Гейт на ЯЗЫК В ТАЙТЛЕ: если язык
# программирования назван в самом названии — это настоящий dev («Python-разработчик в
# продюсерский центр»), и правило молчит. Язык из ОПИСАНИЯ гейт не открывает: «желательно
# знание Python» в JD продюсера не делает его инженером (БАГ 22.07: «Продюсер AI-видео» с
# Python в сниппете прошёл гейт по desc-техам -> отклик ушёл; роль считается ПО ТАЙТЛУ).
# Применяем ДО _ROLE_RX, иначе «\bai\b» из Data/ML промотит креатив в IT (БАГ 21.07).
_CREATIVE_NON_IT = re.compile(
    r'продюсер|режисс|монтажёр|монтажер|видеограф|видеооператор|'
    r'\bsmm\b|маркетолог|контент.?менеджер|копирайтер|таргетолог',
    re.I,
)


# ПОДДЕРЖКА, английская и «сопроводительная» (01.08.2026). Правило про поддержку в
# _HARD_NON_IT знало только русские тайтлы, поэтому «IT Support L3 (IT Administrator)»,
# «helpdesk» и «Инженер сопровождения 1С (L2)» проходили мимо и попадали в IT — часть даже
# в «Разработчика», потому что 1С считается языком и открывала фолбэк по стеку.
#
# Отдельным гейтом, а не строкой в _HARD_NON_IT: тот безусловен, а здесь нужен щадящий
# случай. «Сопровождение» часто дописывают к обязанностям настоящего разработчика
# («Разработчик 1С / Сопровождение 1С», «Инженер-программист по сопровождению 1С»), и
# такие тайтлы прятать нельзя. Замер: паттерн ловит 477 вакансий, из них 8 названы
# разработчиком — их гейт пропускает.
_SUPPORT_NON_IT = re.compile(
    r'\bit support\b|helpdesk|help desk|хелпдеск|\bsupport engineer\b|'
    r'групп\w*\s+поддержк|поддержк\w*\s+(?:1с|бизнес|пользовател|приложен)|'
    # `.{0,15}` ловит слово между, как и в _HARD_NON_IT: «по сопровождению HR платформы»
    r'сопровожден\w*.{0,15}?(?:1с|\bsap\b|платформ)',
    re.I,
)
_DEV_NOUN = re.compile(r'разработчик|программист|\bdeveloper\b', re.I)


def _detect_role(name: str, techs: list[str]) -> Role:
    if _HARD_NON_IT.search(name):
        return Role.NON_IT                      # безусловно не-IT (водитель/курьер/…)
    if _SUPPORT_NON_IT.search(name) and not _DEV_NOUN.search(name):
        return Role.NON_IT                      # поддержка — кроме тайтлов, назвавших разработчика
    if _GIG_NON_IT.search(name):
        return Role.NON_IT                      # крауд-подработка/разметка (AI-тренер/асессор)
    if _CREATIVE_NON_IT.search(name) and not any(t in LANG_KEYS for t in _detect_techs(name)):
        return Role.NON_IT                      # креатив/маркетинг: язык В ТАЙТЛЕ, не в описании
    if not techs and _SOFT_NON_IT.search(name):
        return Role.NON_IT                      # не-IT, если нет тех-тега (химик-разработчик)
    for role, rx in _ROLE_RX:
        if rx.search(name):
            return role                         # уже Role (резолв на импорте, см. _ROLE_RX)
    # Тайтл роль не назвал -> «Разработчик» только при упоминании ЯЗЫКА. Раньше хватало
    # любого тега, и одиночная платформа/ИИ-упоминание («ОС Android», «обучение нейросетей»)
    # производила в разработчики промоутера и мобильного банкира. Язык в требованиях —
    # признак, который у не-инженерных подработок не встречается.
    return Role.DEVELOPER if any(t in LANG_KEYS for t in techs) else Role.NON_IT


def build_vacancy(*, vid: Any, name: Any, city: Any, city_id: Any, salary: Any,
                  experience: Any, schedule: Any, detect_text: Any, employer: Any,
                  created_at: Any, published_at: Any, responses: Any, source: Any,
                  techs: list[str] | None = None) -> Vacancy:
    """Доменная фабрика: собрать Vacancy, посчитав техи (по detect_text) и роль (по тайтлу).
    Единая точка детекции стека/роли для ВСЕХ ACL — и persisted-dict (parse_vacancy),
    и адаптеров источников (hh/hirify). detect_text = тайтл + текст сниппета/карточки.

    `techs` — ГОТОВЫЕ техи из кеша (parse_vacancy, см. DETECT_SIG). Передаются, только
    когда сигнатура словарей совпала; иначе None и считаем заново. Роль от техов дешёвая,
    её всегда считаем здесь — так она не разъедется с текущим ROLE_PATTERNS."""
    if techs is None:
        techs = _detect_techs(detect_text)
    return Vacancy(
        id          = vid,
        name        = name,
        city        = city or '',
        city_id     = city_id or '',
        salary      = salary,
        experience  = experience,
        schedule    = schedule,
        techs       = techs,
        role        = _detect_role(name, techs),
        employer     = employer or '',
        created_at   = created_at,
        published_at = published_at,
        responses    = responses,
        source       = source or 'hh',
    )


def parse_vacancy(raw: dict[str, Any]) -> Vacancy:
    # ACL: persisted raw-dict (схема на диске) -> доменная модель с Value Objects.
    salary = s.net() if (s := Salary.from_raw(raw.get('salary'))) else None   # net внутри VO
    snippet = raw.get('snippet') or {}
    name = raw.get('name', '')
    return build_vacancy(
        vid          = raw['id'],
        name         = name,
        city         = raw.get('_city') or (raw.get('area') or {}).get('name'),
        city_id      = raw.get('_city_id') or (raw.get('area') or {}).get('id', ''),
        salary       = salary,
        experience   = Experience.from_code((raw.get('experience') or {}).get('id', '')),
        schedule     = Schedule.from_code((raw.get('schedule') or {}).get('id', '')) or Schedule.OFFICE,
        detect_text  = ' '.join(filter(None, [
            name, snippet.get('requirement', ''), snippet.get('responsibility', '')])),
        employer     = (raw.get('employer') or {}).get('name', ''),
        created_at   = raw.get('created_at'),
        published_at = raw.get('published_at'),
        responses    = raw.get('responses'),
        source       = raw.get('_source') or 'hh',   # портал-источник (зеркалит _city)
        # Готовые техи из кеша — ТОЛЬКО при совпадении сигнатуры словаря. Детекция стека
        # стоила 46 с из 77 на загрузку 81k записей (1.48 млн re.search), и её результат
        # не меняется, пока не менялись ни текст вакансии, ни TECH_PATTERNS. Текст меняется
        # -> запись перезаписывается сбором целиком; словарь меняется -> не сойдётся
        # DETECT_SIG, и техи пересчитаются сами.
        techs        = raw.get('_techs') if raw.get('_dv') == DETECT_SIG else None,
    )
