"""Value Object формы оформления отношений: ТК РФ/РБ, самозанятость, ИП, ГПХ.

Отвечает на вопрос «как работодатель предлагает оформить сотрудничество». Это НЕ формат
работы (`Schedule` — удалёнка/офис) и НЕ занятость (полная/частичная): вакансия бывает
удалённой И оформленной по ТК, либо офисной И по договору ГПХ.

**Форм может быть НЕСКОЛЬКО одновременно.** «Оформление по ТК РФ или как самозанятый» —
обычная формулировка, и вакансия обязана попасть в оба фильтра сразу. Поэтому детектор
отдаёт КОРТЕЖ (`detect_employment`), а не одно значение: единственная форма заставила бы
выбирать, в какой корзине соврать.

**Два источника, и они складываются.** Основной — структурное поле портала
(`from_hh_fields`: это ровно то, что стоит за фильтром «Оформление» на hh.ru). Второй —
текст описания (`detect_employment`), потому что структурное поле есть только у hh, а
заполняет его не каждый работодатель. Объединение делает `parsing.py::build_vacancy`.

Отсюда контракт, который нельзя ослаблять в UI: пустой кортеж значит «НЕ СКАЗАНО» —
ни полем, ни текстом, — а не «оформления нет».
"""
import hashlib
import re
from enum import Enum
from typing import Any


class Employment(Enum):
    """Форма оформления. Значение = код для raw-схемы, ленты и CSV-отчётов."""

    LABOR_CODE = "labor_code"          # трудовой договор по ТК РФ / ТК РБ
    SELF_EMPLOYED = "self_employed"    # самозанятость (НПД)
    SOLE_TRADER = "sole_trader"        # ИП
    CIVIL_CONTRACT = "civil_contract"  # ГПХ, договор подряда

    @property
    def code(self) -> str:
        """Код для ленты/хранения/CSV (единый идентификатор во всех слоях)."""
        return self.value

    @property
    def label(self) -> str:
        """Подпись для человека. Живёт ЗДЕСЬ, а не в `config`, в отличие от `EXP_LABELS`:
        новый VO не повторяет известный компромисс `Experience.label` (доменный модуль
        тянет `hrwork.config` с его mkdir/load_dotenv, см. `docs/domain.md`)."""
        return _LABELS[self]

    @classmethod
    def from_code(cls, code: str | None) -> "Employment | None":
        """МЯГКИЙ парсер сохранённого кода -> форма. Пусто/незнакомое -> None.
        Единый контракт с `Schedule.from_code` / `Experience.from_code`: парсер внешних
        данных возвращает VO|None и не выдумывает значение."""
        try:
            return cls(code) if code else None
        except ValueError:
            return None

    @classmethod
    def from_hh_fields(cls, accept_labor_contract: Any,
                       civil_law_contracts: list[dict[str, Any]] | None) -> tuple["Employment", ...]:
        """Структурные поля hh -> формы оформления. ЕДИНСТВЕННАЯ точка, где живёт словарь
        портала: адаптер лишь достаёт два поля из своей схемы, что они значат — знает домен
        (то же правило, что у `Schedule.from_hh_formats` и `Experience.from_grades`).

        Это ТО САМОЕ поле, что стоит за фильтром «Оформление» на hh.ru; разведка 10.08.2026
        нашла его в состоянии страницы поиска (`HH-Lux-InitialState`):
          * `acceptLaborContract: bool` -> ТК РФ/РБ;
          * `civilLawContracts[].civilLawContractsElement[]` -> `SELF_EMPLOYED` (самозанятый),
            `INDIVIDUAL_ENTREPRENEUR` (ИП), `INDIVIDUAL_PERSON` (договор ГПХ с физлицом).
        Незнакомый код молча пропускается: hh волен завести пятый, и падать на нём сбор
        не должен — контракт мягкого парсера внешних данных.

        Пустой кортеж значит «работодатель не заполнил», а не «оформления нет»: у 444 из 712
        вакансий замера `acceptLaborContract` был False при пустом `civilLawContracts`."""
        out = [cls.LABOR_CODE] if accept_labor_contract else []
        codes = {code
                 for block in (civil_law_contracts or [])
                 for value in (block or {}).values()
                 for code in (value if isinstance(value, list) else [value])}
        out += [emp for hh_code, emp in _HH_CIVIL.items() if hh_code in codes]
        return tuple(emp for emp in cls if emp in out)     # канонический порядок

    @classmethod
    def from_label(cls, label: str) -> "Employment":
        """СТРОГИЙ парсер подписи -> форма; незнакомая подпись роняет с ValueError.
        Для НАШИХ констант (чипы ленты, заголовки CSV): дрейф подписи обязан падать
        громко, а не превращаться в тихий None. Контракт как у `Role.from_label`."""
        try:
            return _BY_LABEL[label]
        except KeyError:
            raise ValueError(f"неизвестная форма оформления: {label!r}") from None


_LABELS: dict[Employment, str] = {
    Employment.LABOR_CODE: "ТК РФ/РБ",
    Employment.SELF_EMPLOYED: "Самозанятый",
    Employment.SOLE_TRADER: "ИП",
    Employment.CIVIL_CONTRACT: "ГПХ",
}
_BY_LABEL: dict[str, Employment] = {lbl: emp for emp, lbl in _LABELS.items()}

# Словарь hh для `civilLawContractsElement` (см. `Employment.from_hh_fields`).
# `INDIVIDUAL_PERSON` — это договор с ФИЗЛИЦОМ, то есть ГПХ: на самом hh.ru эта галочка
# и подписана «ГПХ». Отдельным членом enum физлицо не заводится — для соискателя «ГПХ
# с физлицом» и «договор ГПХ» это одна и та же форма, а лишний чип дробил бы фильтр.
_HH_CIVIL: dict[str, Employment] = {
    "SELF_EMPLOYED": Employment.SELF_EMPLOYED,
    "INDIVIDUAL_ENTREPRENEUR": Employment.SOLE_TRADER,
    "INDIVIDUAL_PERSON": Employment.CIVIL_CONTRACT,
}


# ── Детектор по тексту ────────────────────────────────────────────────────────────────
# Паттерны намеренно РАЗНОЙ строгости, и строгость каждого ЗАМЕРЕНА на 128 752 описаниях
# 10.08.2026 (по 12 контекстов на паттерн, глазами). Что дал замер:
#
# * «самозанят» (359) и «гпх» (316) — термины, вне темы оформления не встречающиеся:
#   ложных в выборке ноль, поэтому ловятся голым вхождением;
# * «НПД» отвергнут: 2 срабатывания на всю базу, и оба про «нормативно-правовую
#   документацию» в стройке, а не про налог на профессиональный доход;
# * «договор подряда» отвергнут: 38 срабатываний, и выборка сразу дала ложное —
#   «заключение договоров подряда» это ОБЯЗАННОСТЬ инженера-строителя, а не форма
#   оформления. Реальные случаи и так подписаны словом «ГПХ»;
# * «трудоустройство» (7 619) взято, но ТОЛЬКО в связке «официальное» / «по» / «согласно»:
#   голое слово ловило бы рекламу кадровых агентств («поможем с трудоустройством»),
#   а все 12 контекстов выборки имели связку;
# * «ИП» — самый частый двухбуквенный токен русских вакансий, и голый токен (354) сразу
#   дал ложное: «О компании ИП Ляпин — ведущий дистрибьютор» это ФОРМА РАБОТОДАТЕЛЯ,
#   а не предложение оформить ИСПОЛНИТЕЛЯ как ИП. Поэтому нужен контекст оформления
#   слева. Через `\s+` он не годится: реальные формулировки разделены пунктуацией
#   («Оформление: ИП», «самозанятый / ИП»), поэтому окно — 25 символов ВНУТРИ
#   предложения (`[^.;!?]`), чтобы контекст не перетекал из соседней фразы.
#
# Обратная сторона строгости принята сознательно: лучше недобрать в «не указано»
# (честное «портал не сказал»), чем записать в «ИП» вакансию по названию работодателя.
_PATTERNS: dict[Employment, str] = {
    Employment.LABOR_CODE: (
        r"\bтк\s*р[фб]\b"                          # ТК РФ, ТК РБ, ТКРФ
        r"|трудов\w*\s+кодекс"
        r"|трудов\w*\s+договор"                    # «по Трудовому договору»
        r"|оформлени\w*\s+по\s+тк\b"               # «оформление по ТК» без РФ/РБ
        r"|официальн\w*\s+трудоустройств"
        r"|трудоустройств\w*\s+(?:по|в\s+соответствии|согласно)"
    ),
    Employment.SELF_EMPLOYED: r"самозанят",
    Employment.SOLE_TRADER: (
        r"индивидуальн\w*\s+предпринимател"        # полное название — контекст не нужен
        r"|(?:оформлен\w*|сотрудничеств\w*|самозанят\w*|договор\w*"
        r"|статус\w*|качестве|через|открыт\w*|регистрац\w*)[^.;!?]{0,25}?\bип\b"
    ),
    Employment.CIVIL_CONTRACT: r"\bгпх\b|гражданско.?правов",
}
_RX: dict[Employment, re.Pattern[str]] = {
    emp: re.compile(rx, re.I) for emp, rx in _PATTERNS.items()
}


def detect_employment(text: str) -> tuple[Employment, ...]:
    """Текст вакансии -> формы оформления, упомянутые в нём, в порядке объявления enum.

    Порядок КАНОНИЧЕСКИЙ (порядок членов `Employment`), а не порядок вхождения в текст:
    результат кладётся в кеш и сравнивается на равенство, поэтому «ТК и самозанятость»
    обязано давать один и тот же кортеж независимо от того, что упомянуто раньше.

    Пустой кортеж = в тексте формы НЕТ. Домыслить сюда ТК «по умолчанию, раз это hh»
    нельзя — это ровно та ошибка, из-за которой безгрейдовые вакансии едва не получили
    подпись «Без опыта» (см. `views/feed.py::EXP_UNKNOWN`)."""
    if not text:
        return ()
    return tuple(emp for emp, rx in _RX.items() if rx.search(text))


# Сигнатура словаря форм. Формы кешируются в raw (`_emp`), и правка паттернов обязана
# протухать кеш САМА — иначе лента месяцами показывала бы разбор по старым правилам.
# Сигнатура ОТДЕЛЬНАЯ от `parsing.DETECT_SIG` (стек) намеренно: словари правятся
# независимо, а общая сигнатура заставляла бы пересчитывать 128 тыс. записей на
# детекции стека (46 с) из-за правки одного слова про ИП.
_DETECT_ALGO_VERSION = 1
EMPLOYMENT_SIG = hashlib.blake2s(
    (repr(sorted((e.value, p) for e, p in _PATTERNS.items()))
     + f"|v{_DETECT_ALGO_VERSION}").encode("utf-8"),
    digest_size=6,
).hexdigest()
