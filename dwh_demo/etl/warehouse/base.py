"""Порт «хранилище данных». Любой бэкенд (Postgres, ClickHouse, …) реализует
этот контракт и инжектится в Pipeline — конвейер не знает, куда грузит."""
from __future__ import annotations

from typing import Protocol, runtime_checkable

from ..domain import Vacancy


@runtime_checkable
class Warehouse(Protocol):
    name: str

    def init_schema(self) -> None:
        """Создать/обновить схему (идемпотентно)."""

    def load(self, vacancies: list[Vacancy]) -> int:
        """Полностью заменить факт переданными вакансиями (идемпотентно).

        ВОЗВРАЩАЕТ число строк, оказавшихся В ФАКТЕ ПОСЛЕ загрузки, — прочитанное ИЗ
        ХРАНИЛИЩА (`SELECT count(...)`), а не длину входа и не число отправленных строк.
        На этом числе держится главная проверка проекта: `Pipeline._verify` сверяет его
        с результатом `prepare` по каждому движку. Адаптер, возвращающий `len(vacancies)`,
        делает сверку вакуумной — она совпадёт, что бы ни случилось в базе (так и было
        в ClickHouse до 09.08.2026).

        Реализация обязана описать в докстринге политику восстановления: атомарна ли
        замена факта и безопасен ли повтор после обрыва."""

    def count(self) -> int:
        """Число вакансий в факте. Кроме верификации, служит базой санити-гейта
        `Pipeline._reject_degraded`: перезалив отменяется, если новый срез просел
        относительно этого числа больше чем вдвое."""
