"""Конфиги подпроекта читаются теми инструментами, для которых написаны.

Проверять конфиг тестом кажется избыточным ровно до первого раза, когда инструмент
падает не там, где ошибка.
"""
from pathlib import Path

import pytest

pytestmark = pytest.mark.unit

_ROOT = Path(__file__).resolve().parents[1]


def test_mypy_config_survives_a_cp1251_locale() -> None:
    """`mypy.ini` обязан читаться в cp1251, хотя лежит в UTF-8.

    Инцидент 09.08.2026, стоивший получаса. mypy читает конфиг через `configparser`,
    то есть кодировкой ЛОКАЛИ, а на машине разработки это cp1251. Почти любой русский
    текст такое чтение переживает — превращается в мусор, но mypy комментарии и не нужны.
    Кроме одного байта: 0x98 в cp1251 НЕ ОПРЕДЕЛЁН, и именно он стоит вторым в UTF-8
    у заглавной русской «и» (D0 98). Одна такая буква В КОММЕНТАРИИ роняет mypy
    с UnicodeDecodeError ещё до разбора конфига, и падение выглядит как поломка самого
    mypy, а не как опечатка в тексте.

    У родителя того же байта нет СЛУЧАЙНО, а не по правилу, поэтому страж стоит здесь.
    Проверяем cp1251 явно, а не «локаль текущей машины»: на Linux-CI локаль UTF-8,
    и тест, спрашивающий про неё, ловушку бы пропустил.
    """
    raw = (_ROOT / "mypy.ini").read_bytes()
    raw.decode("cp1251")


@pytest.mark.parametrize("name", ["mypy.ini", "pytest.ini", "ruff.toml"])
def test_config_is_valid_utf8(name: str) -> None:
    # Вторая половина того же контракта: файл лежит в UTF-8, и редактор с git видят
    # текст, а не мусор. Ловушка выше — про ЧТЕНИЕ инструментом, эта — про хранение.
    (_ROOT / name).read_bytes().decode("utf-8")
